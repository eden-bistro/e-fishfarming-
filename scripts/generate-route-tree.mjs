import { readFile, writeFile } from "node:fs/promises";
import { Generator, getConfig } from "@tanstack/router-generator";

const generatedRouteTree = "./src/routeTree.gen.ts";
const tanstackStartRegisterNeedle = "declare module '@tanstack/react-start'";
const tanstackStartRegisterAugmentation = `import type { getRouter } from './router.tsx'
import type { startInstance } from './start.ts'
declare module '@tanstack/react-start' {
  interface Register {
    ssr: true
    router: Awaited<ReturnType<typeof getRouter>>
    config: Awaited<ReturnType<typeof startInstance.getOptions>>
  }
}`;

const config = getConfig(
  {
    routesDirectory: "./src/routes",
    generatedRouteTree,
    quoteStyle: "single",
    semicolons: false,
    disableLogging: true,
  },
  process.cwd(),
);

const generator = new Generator({ config, root: process.cwd() });
await generator.run();

let routeTreeSource = await readFile(generatedRouteTree, "utf8");

function countOccurrences(haystack, needle) {
  return haystack.split(needle).length - 1;
}

if (countOccurrences(routeTreeSource, tanstackStartRegisterNeedle) === 0) {
  routeTreeSource = `${routeTreeSource.trimEnd()}\n\n${tanstackStartRegisterAugmentation}\n`;
  await writeFile(generatedRouteTree, routeTreeSource);
}

const routeTreeShapeChecks = [
  {
    label: "TanStack generated file banner",
    needle: "This file was automatically generated by TanStack Router.",
    expectedCount: 1,
  },
  {
    label: "rootRouteChildren declaration",
    needle: "const rootRouteChildren: RootRouteChildren =",
    expectedCount: 1,
  },
  {
    label: "TanStack Start register augmentation",
    needle: tanstackStartRegisterNeedle,
    expectedCount: 1,
  },
];

const duplicateMessages = routeTreeShapeChecks
  .map(({ label, needle, expectedCount }) => ({
    label,
    count: countOccurrences(routeTreeSource, needle),
    expectedCount,
  }))
  .filter(({ count, expectedCount }) => count !== expectedCount)
  .map(({ label, count }) => `${label} appeared ${count} times`);

if (duplicateMessages.length > 0) {
  throw new Error(
    `Generated route tree looks duplicated or incomplete: ${duplicateMessages.join(", ")}`,
  );
}
