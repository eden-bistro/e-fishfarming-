create table if not exists feeding_events (
  id bigint generated by default as identity primary key,
  timestamp timestamptz not null,
  pond_id text not null,
  mode text not null,
  amount_kg numeric not null,
  status text not null,
  created_at timestamptz not null default now()
);

create table if not exists water_readings (
  id bigint generated by default as identity primary key,
  timestamp timestamptz not null,
  pond_id text not null,
  temperature numeric,
  ph numeric,
  dissolved_oxygen numeric,
  turbidity numeric,
  ammonia numeric,
  nitrite numeric,
  raw_payload jsonb,
  created_at timestamptz not null default now()
);

create table if not exists finance_income (
  id bigint generated by default as identity primary key,
  date date not null,
  buyer text not null,
  quantity_kg numeric not null,
  price_per_kg numeric not null,
  total numeric not null,
  created_at timestamptz not null default now()
);

create table if not exists finance_expenses (
  id bigint generated by default as identity primary key,
  date date not null,
  category text not null,
  description text not null,
  amount numeric not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_water_readings_pond_time on water_readings (pond_id, timestamp desc);
create index if not exists idx_income_date on finance_income (date desc);
create index if not exists idx_expenses_date on finance_expenses (date desc);
